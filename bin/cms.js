#!/usr/bin/env node
/**
 * CLI of @medienakzent/cms
 *
 *   cms init [directory] [--name <package-name>]   scaffold a customer project (project files + stubs)
 *   cms sync [--force] [--quiet]                   bring stubs (routes, hooks) up to the package version
 *   cms check                                      verify stubs, report customer-modified files
 *   cms update [--major] [--dry-run]               pin the newest releases of cms and ui
 *   cms lock                                       rewrite package-lock.json for all platforms
 *   cms postinstall                                internal: sync after npm install/update
 *
 * Stubs are generated files without own logic (header "@generated"). The manifest
 * .cms/manifest.json stores the hash of the generated content per stub and marks files
 * the customer modified. Only unmodified stubs are replaced or removed on updates;
 * modified ones are kept and reported. Project files (templates/project) are created
 * by `init` once and never touched again.
 */
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import {
	appendFileSync,
	chmodSync,
	copyFileSync,
	existsSync,
	mkdtempSync,
	mkdirSync,
	readdirSync,
	readFileSync,
	rmSync,
	writeFileSync
} from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const PACKAGE_DIR = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const PACKAGE = JSON.parse(readFileSync(join(PACKAGE_DIR, 'package.json'), 'utf8'));
const TEMPLATES_DIR = join(PACKAGE_DIR, 'templates');
const MANIFEST_PATH = '.cms/manifest.json';
const GENERATED_MARKER = '@generated by @medienakzent/cms';
const FLAGS_WITH_VALUE = new Set(['--name']);

const args = process.argv.slice(2);
const command = args[0];
const flags = new Set(args.filter((arg) => arg.startsWith('--')));
const positional = args
	.slice(1)
	.filter((arg, index, all) => !arg.startsWith('--') && !FLAGS_WITH_VALUE.has(all[index - 1]));
const quiet = flags.has('--quiet');

function flagValue(name) {
	const index = args.indexOf(name);
	return index >= 0 ? args[index + 1] : undefined;
}

function log(...message) {
	if (!quiet) console.log(...message);
}

function walk(directory, base = directory) {
	const files = [];
	for (const entry of readdirSync(directory, { withFileTypes: true })) {
		const full = join(directory, entry.name);
		if (entry.isDirectory()) files.push(...walk(full, base));
		else files.push(relative(base, full).split(sep).join('/'));
	}
	return files.sort();
}

const sha1 = (content) => createHash('sha1').update(content).digest('hex');

function header(file) {
	const note = `${GENERATED_MARKER} ${PACKAGE.version} — do not edit, replaced on updates (npx cms sync)`;
	return file.endsWith('.svelte') ? `<!-- ${note} -->\n` : `// ${note}\n`;
}

function readManifest(root) {
	try {
		return JSON.parse(readFileSync(join(root, MANIFEST_PATH), 'utf8'));
	} catch {
		return { version: null, files: {} };
	}
}

function writeManifest(root, manifest) {
	mkdirSync(join(root, '.cms'), { recursive: true });
	writeFileSync(join(root, MANIFEST_PATH), JSON.stringify(manifest, null, '\t') + '\n');
}

/** Manifest entries were plain hashes before 0.4.1. */
function manifestEntry(value) {
	return typeof value === 'string' ? { hash: value, modified: false } : value;
}

function isProject(root) {
	return existsSync(join(root, 'src', 'cms.config.ts')) || existsSync(join(root, MANIFEST_PATH));
}

function removeEmptyDirectories(from, root) {
	let directory = from;
	while (directory !== root && existsSync(directory) && readdirSync(directory).length === 0) {
		rmSync(directory, { recursive: true });
		directory = dirname(directory);
	}
}

/** Write stubs. Customer-modified stubs stay marked and are only replaced with --force. */
function sync(root, { force = false } = {}) {
	const stubsDir = join(TEMPLATES_DIR, 'stubs');
	const manifest = readManifest(root);
	const next = { version: PACKAGE.version, files: {} };
	const result = { written: [], skipped: [], removed: [], unchanged: [] };

	for (const file of walk(stubsDir)) {
		const content = header(file) + readFileSync(join(stubsDir, file), 'utf8');
		const hash = sha1(content);
		const target = join(root, file);
		const known = manifest.files[file] ? manifestEntry(manifest.files[file]) : null;
		if (existsSync(target)) {
			const currentContent = readFileSync(target, 'utf8');
			const currentHash = sha1(currentContent);
			if (currentHash === hash) {
				next.files[file] = { hash, modified: false };
				result.unchanged.push(file);
				continue;
			}
			const modified = known
				? known.modified || currentHash !== known.hash
				: !currentContent.includes(GENERATED_MARKER);
			if (modified && !force) {
				next.files[file] = { hash, modified: true };
				result.skipped.push(file);
				continue;
			}
		}
		mkdirSync(dirname(target), { recursive: true });
		writeFileSync(target, content);
		next.files[file] = { hash, modified: false };
		result.written.push(file);
	}

	for (const [file, value] of Object.entries(manifest.files)) {
		if (next.files[file]) continue;
		const target = join(root, file);
		if (!existsSync(target)) continue;
		const known = manifestEntry(value);
		const currentHash = sha1(readFileSync(target, 'utf8'));
		if (force || (!known.modified && currentHash === known.hash)) {
			rmSync(target);
			removeEmptyDirectories(dirname(target), root);
			result.removed.push(file);
		} else {
			next.files[file] = { hash: known.hash, modified: true };
			result.skipped.push(file);
		}
	}

	if (root !== PACKAGE_DIR) {
		const name = projectName(root);
		for (const file of missingOperationalFiles(root))
			result.written.push(writeProjectFile(root, file, name));
	}

	writeManifest(root, next);
	return result;
}

function report(result, previousVersion) {
	if (previousVersion && previousVersion !== PACKAGE.version) {
		log(`@medienakzent/cms: Stubs von ${previousVersion} auf ${PACKAGE.version} aktualisiert.`);
	}
	for (const file of result.written) log(`  + ${file}`);
	for (const file of result.removed) log(`  - ${file}`);
	for (const file of result.skipped) {
		console.warn(
			`  ! ${file} wurde geändert und bleibt stehen — mit \`npx cms sync --force\` ersetzen`
		);
	}
	if (!result.written.length && !result.removed.length && !result.skipped.length) {
		log('@medienakzent/cms: Stubs sind aktuell.');
	}
}

/** Path of a project template file inside the project (npm strips dotfiles from packages). */
function projectTarget(file) {
	return file
		.replace(/^_gitignore$/, '.gitignore')
		.replace(/^_npmrc$/, '.npmrc')
		.replace(/^_github\//, '.github/');
}

function renderProjectFile(file, name) {
	return readFileSync(join(TEMPLATES_DIR, 'project', file), 'utf8')
		.replaceAll('__PROJECT_NAME__', name)
		.replaceAll('__DEV_HOST__', `${name.replace(/^cms[.-]/, '')}.test`)
		.replaceAll('__CMS_VERSION__', PACKAGE.version);
}

function writeProjectFile(root, file, name) {
	const target = join(root, projectTarget(file));
	mkdirSync(dirname(target), { recursive: true });
	writeFileSync(target, renderProjectFile(file, name));
	if (target.endsWith('.sh')) chmodSync(target, 0o755);
	return relative(root, target);
}

/**
 * Operational files from the project template that later releases added: `cms sync` creates them
 * in existing projects when missing and never overwrites them (projects may adapt them).
 */
const OPERATIONAL_FILES = ['app.cjs', 'plesk-deploy.sh', '_github/workflows/cms-update.yml'];

function projectName(root) {
	try {
		return JSON.parse(readFileSync(join(root, 'package.json'), 'utf8')).name ?? 'cms';
	} catch {
		return 'cms';
	}
}

function missingOperationalFiles(root) {
	return OPERATIONAL_FILES.filter((file) => !existsSync(join(root, projectTarget(file))));
}

function copyProject(root, { name }) {
	const projectDir = join(TEMPLATES_DIR, 'project');
	const created = [];
	const kept = [];
	for (const file of walk(projectDir)) {
		const target = join(root, projectTarget(file));
		if (existsSync(target)) {
			kept.push(relative(root, target));
			continue;
		}
		created.push(writeProjectFile(root, file, name));
	}
	return { created, kept };
}

/**
 * Native modules must be direct dependencies of the project: adapter-node bundles everything
 * else into the server build, where they fail at runtime (__filename is not defined).
 */
const NATIVE_DEPENDENCIES = ['better-sqlite3', 'sharp'];

function missingNativeDependencies(root) {
	const projectFile = join(root, 'package.json');
	if (!existsSync(projectFile)) return [];
	const project = JSON.parse(readFileSync(projectFile, 'utf8'));
	return NATIVE_DEPENDENCIES.filter((name) => !project.dependencies?.[name]).map(
		(name) => `"${name}": "${PACKAGE.dependencies[name]}"`
	);
}

/**
 * Git dependencies must point at prebuilt releases (tags `release/vX.Y.Z`): a plain source tag
 * makes npm run `prepare` with all devDependencies on every install, which breaks on servers
 * without `node` in PATH (Plesk/nodenv) and slows every deployment down.
 */
const RELEASE_DEPENDENCIES = ['@medienakzent/cms', '@compdata/ui'];

function sourceDependencies(root) {
	const projectFile = join(root, 'package.json');
	if (!existsSync(projectFile)) return [];
	const project = JSON.parse(readFileSync(projectFile, 'utf8'));
	const dependencies = { ...project.dependencies, ...project.devDependencies };
	return RELEASE_DEPENDENCIES.filter((name) => {
		const specification = dependencies[name];
		return specification?.startsWith('github:') && !specification.includes('#release/');
	}).map((name) => `${name} (${dependencies[name]})`);
}

/** Releases carry no install scripts, so the project itself must sync the stubs on install. */
function syncsOnInstall(root) {
	const projectFile = join(root, 'package.json');
	if (!existsSync(projectFile)) return true;
	const scripts = JSON.parse(readFileSync(projectFile, 'utf8')).scripts ?? {};
	return [scripts.prepare, scripts.postinstall].some((script) => script?.includes('cms sync'));
}

function warnNativeDependencies(missing) {
	console.warn(
		`package.json: unter "dependencies" fehlt ${missing.join(', ')} — sonst stürzt der Produktions-Build (node build) ab. Eintragen, dann npm install.`
	);
}

const GIT_RELEASE = /^github:([\w.-]+\/[\w.-]+)#release\/v(\d+\.\d+\.\d+)$/;
const RELEASE_TAG = /^refs\/tags\/release\/v(\d+\.\d+\.\d+)$/;

const parseVersion = (version) => version.split('.').map(Number);

function compareVersions(left, right) {
	for (let index = 0; index < 3; index++) {
		if (left[index] !== right[index]) return left[index] - right[index];
	}
	return 0;
}

/** Release versions of a GitHub repository, read from its tags (no clone). */
function releaseVersions(repository) {
	const output = execFileSync(
		'git',
		['ls-remote', '--tags', `git@github.com:${repository}.git`, 'refs/tags/release/v*'],
		{ encoding: 'utf8', stdio: ['ignore', 'pipe', 'inherit'] }
	);
	return output
		.split('\n')
		.map((line) => line.split('\t')[1]?.match(RELEASE_TAG)?.[1])
		.filter(Boolean)
		.map(parseVersion);
}

/**
 * Pins the newest prebuilt releases of cms and ui in package.json and the lockfile. Stays within
 * the current major version unless `major` is set, so breaking releases never arrive unasked.
 */
function update(root, { major, dryRun }) {
	const projectFile = join(root, 'package.json');
	let raw = readFileSync(projectFile, 'utf8');
	const project = JSON.parse(raw);
	const changes = [];
	for (const name of RELEASE_DEPENDENCIES) {
		const specification = project.dependencies?.[name] ?? project.devDependencies?.[name];
		if (!specification) continue;
		const match = specification.match(GIT_RELEASE);
		if (!match) {
			console.warn(
				`${name}: ${specification} ist kein Release-Tag (#release/vX.Y.Z), übersprungen.`
			);
			continue;
		}
		const [, repository, currentVersion] = match;
		const current = parseVersion(currentVersion);
		const newest = releaseVersions(repository)
			.filter((version) => major || version[0] === current[0])
			.sort(compareVersions)
			.at(-1);
		if (!newest || compareVersions(newest, current) <= 0) {
			log(`${name} ${currentVersion} ist aktuell.`);
			continue;
		}
		const version = newest.join('.');
		raw = raw.replace(
			JSON.stringify(specification),
			JSON.stringify(`github:${repository}#release/v${version}`)
		);
		changes.push({ name, from: currentVersion, to: version });
	}
	if (!changes.length || dryRun) return changes;

	writeFileSync(projectFile, raw);
	regenerateLockfile(
		root,
		changes.map((change) => change.name)
	);
	return changes;
}

/**
 * Native packages that the Linux x64 servers (Plesk, Docker) need. npm records only the packages of
 * its own platform when it writes the lockfile next to an existing node_modules (npm/cli#4828), e.g.
 * in an arm64 dev container; the build then fails on the server with "Cannot find module
 * @rollup/rollup-linux-x64-gnu".
 */
const LINUX_PACKAGES = ['@rollup/rollup-linux-x64-gnu', '@esbuild/linux-x64'];

function missingLinuxPackages(lockFile) {
	if (!existsSync(lockFile)) return [];
	const packages = JSON.parse(readFileSync(lockFile, 'utf8')).packages ?? {};
	const paths = Object.keys(packages);
	return LINUX_PACKAGES.filter((name) => {
		const parent = name.startsWith('@rollup/') ? 'rollup' : 'esbuild';
		const usesParent = paths.some((path) => path.endsWith(`node_modules/${parent}`));
		return usesParent && !paths.some((path) => path.endsWith(`node_modules/${name}`));
	});
}

/**
 * Writes the lockfile in an empty directory, so npm records the native packages of all platforms.
 * Locked git dependencies in `refresh` are dropped first (npm keeps locked commits otherwise); if
 * platform packages are still missing, the lockfile is resolved again from scratch.
 */
function regenerateLockfile(root, refresh = []) {
	const workspace = mkdtempSync(join(tmpdir(), 'cms-lock-'));
	const lockFile = join(root, 'package-lock.json');
	const run = () =>
		execFileSync(
			'npm',
			['install', '--package-lock-only', '--ignore-scripts', '--no-audit', '--no-fund'],
			{ cwd: workspace, stdio: quiet ? 'ignore' : 'inherit' }
		);
	try {
		for (const name of ['package.json', '.npmrc']) {
			if (existsSync(join(root, name))) copyFileSync(join(root, name), join(workspace, name));
		}
		if (existsSync(lockFile)) {
			const lockRaw = readFileSync(lockFile, 'utf8');
			const lockfile = JSON.parse(lockRaw);
			for (const name of refresh) delete lockfile.packages?.[`node_modules/${name}`];
			const indent = lockRaw.match(/^[ \t]+/m)?.[0] ?? '  ';
			writeFileSync(
				join(workspace, 'package-lock.json'),
				JSON.stringify(lockfile, null, indent) + '\n'
			);
		}
		run();
		if (missingLinuxPackages(join(workspace, 'package-lock.json')).length) {
			rmSync(join(workspace, 'package-lock.json'));
			run();
		}
		copyFileSync(join(workspace, 'package-lock.json'), lockFile);
	} finally {
		rmSync(workspace, { recursive: true, force: true });
	}
}

function check(root) {
	const manifest = readManifest(root);
	let problems = 0;
	const missing = missingNativeDependencies(root);
	if (missing.length) {
		warnNativeDependencies(missing);
		problems++;
	}
	if (root !== PACKAGE_DIR && !syncsOnInstall(root)) {
		console.warn(
			'package.json: "prepare" ruft "cms sync --quiet" nicht auf — die vorgebauten Releases bringen kein postinstall mit, Stubs würden nach Updates nicht nachgezogen. Vorlage: "prepare": "cms sync --quiet && (svelte-kit sync || true)".'
		);
		problems++;
	}
	const unbuilt = sourceDependencies(root);
	if (unbuilt.length && root !== PACKAGE_DIR) {
		console.warn(
			`package.json: ${unbuilt.join(', ')} ${unbuilt.length === 1 ? 'zeigt' : 'zeigen'} auf einen Quell-Tag — bitte das vorgebaute Release pinnen (#release/vX.Y.Z), sonst baut npm das Paket bei jeder Installation.`
		);
		problems++;
	}
	const linuxPackages = missingLinuxPackages(join(root, 'package-lock.json'));
	if (linuxPackages.length) {
		console.warn(
			`package-lock.json: ${linuxPackages.join(', ')} ${linuxPackages.length === 1 ? 'fehlt' : 'fehlen'} — das Lockfile wurde neben node_modules auf einer anderen Plattform erzeugt, der Build auf Linux-Servern scheitert. Reparieren: npx cms lock`
		);
		problems++;
	}
	if (root !== PACKAGE_DIR) {
		const missingFiles = missingOperationalFiles(root).map(projectTarget);
		if (missingFiles.length) {
			console.warn(
				`fehlt: ${missingFiles.join(', ')} — npx cms sync legt fehlende Dateien aus der Vorlage an.`
			);
			problems++;
		}
	}
	if (manifest.version !== PACKAGE.version) {
		console.warn(
			`Stubs stammen von ${manifest.version ?? 'unbekannt'}, installiert ist ${PACKAGE.version} — npx cms sync ausführen.`
		);
		problems++;
	}
	for (const file of walk(join(TEMPLATES_DIR, 'stubs'))) {
		const target = join(root, file);
		const known = manifest.files[file] ? manifestEntry(manifest.files[file]) : null;
		if (!existsSync(target)) {
			console.warn(`fehlt: ${file}`);
			problems++;
		} else if (known && (known.modified || sha1(readFileSync(target, 'utf8')) !== known.hash)) {
			console.warn(`geändert (wird bei Updates nicht ersetzt): ${file}`);
			problems++;
		}
	}
	console.log(
		problems
			? `${problems} ${problems === 1 ? 'Problem' : 'Probleme'}.`
			: 'Alle Stubs aktuell und unverändert.'
	);
	return problems;
}

switch (command) {
	case 'init': {
		const root = resolve(positional[0] ?? '.');
		const name =
			flagValue('--name') ??
			root
				.split(sep)
				.pop()
				.toLowerCase()
				.replace(/[^a-z0-9-]+/g, '-');
		mkdirSync(root, { recursive: true });
		const { created, kept } = copyProject(root, { name });
		const result = sync(root);
		log(`@medienakzent/cms ${PACKAGE.version}: Projekt „${name}" in ${root}`);
		for (const file of created) log(`  + ${file}`);
		for (const file of kept) log(`  = ${file} (vorhanden, unverändert gelassen)`);
		report(result, null);
		log(`
Nächste Schritte:
  cd ${relative(process.cwd(), root) || '.'}
  cp .env.example .env            # AUTH_SECRET und Mail-Einstellungen setzen
  docker compose -f docker-compose.dev.yml up -d --build
  → http://localhost:5173 bzw. https://${name.replace(/^cms[.-]/, '')}.test über den lokalen Proxy; /admin (erster Nutzer wird Admin)
Eigene Inhaltstypen: src/blocks, src/collections, src/mail — siehe AGENTS.md.`);
		break;
	}
	case 'sync': {
		const root = process.cwd();
		if (!isProject(root)) {
			console.error('Kein CMS-Projekt (src/cms.config.ts fehlt). Zuerst: npx cms init');
			process.exit(1);
		}
		const previousVersion = readManifest(root).version;
		report(sync(root, { force: flags.has('--force') }), previousVersion);
		break;
	}
	case 'lock': {
		const root = process.cwd();
		if (!existsSync(join(root, 'package.json'))) {
			console.error('Keine package.json im aktuellen Verzeichnis.');
			process.exit(1);
		}
		regenerateLockfile(root);
		const missing = missingLinuxPackages(join(root, 'package-lock.json'));
		console.log(
			missing.length
				? `Lockfile neu, es fehlt weiterhin: ${missing.join(', ')}`
				: 'Lockfile neu erzeugt, alle Plattformen enthalten.'
		);
		process.exit(missing.length ? 1 : 0);
	}
	case 'update': {
		const root = process.cwd();
		if (!isProject(root)) {
			console.error('Kein CMS-Projekt (src/cms.config.ts fehlt).');
			process.exit(1);
		}
		const dryRun = flags.has('--dry-run');
		const changes = update(root, { major: flags.has('--major'), dryRun });
		for (const change of changes) console.log(`${change.name}: ${change.from} → ${change.to}`);
		if (!changes.length) console.log('Alle Releases sind aktuell.');
		else if (dryRun) console.log('Nur angezeigt (--dry-run), nichts geändert.');
		else
			console.log(
				'package.json und Lockfile angepasst. Danach installieren (Dev-Container neu starten bzw. npm ci), npm run check.'
			);
		// GitHub Actions: lets the workflow decide whether to build and commit.
		if (process.env.GITHUB_OUTPUT && !dryRun) {
			const summary = changes.map((change) => `${change.name} ${change.to}`).join(', ');
			appendFileSync(
				process.env.GITHUB_OUTPUT,
				`changed=${changes.length ? 'true' : 'false'}\nsummary=Update auf ${summary || 'aktuellen Stand'}\n`
			);
		}
		break;
	}
	case 'check':
		process.exit(check(process.cwd()) ? 1 : 0);
		break;
	case 'postinstall': {
		const root = process.env.INIT_CWD ? resolve(process.env.INIT_CWD) : null;
		if (!root || root === PACKAGE_DIR || !isProject(root)) break;
		const previousVersion = readManifest(root).version;
		const result = sync(root);
		if (result.written.length || result.removed.length || result.skipped.length)
			report(result, previousVersion);
		const missing = missingNativeDependencies(root);
		if (missing.length) warnNativeDependencies(missing);
		break;
	}
	default:
		console.log(
			`@medienakzent/cms ${PACKAGE.version}\n\n  cms init [verzeichnis] [--name paketname]\n  cms sync [--force] [--quiet]\n  cms check\n  cms update [--major] [--dry-run]\n  cms lock`
		);
		process.exit(command ? 1 : 0);
}
